import turtle
import colorsys
import random

def colorful():
    screen = turtle.Screen()
    screen.bgcolor("black")  # Βάζουμε μαύρο φόντο, για να θυμίζει το διάστημα
    screen.title("Colorful")  # Τίτλος παραθύρου

    t = turtle.Turtle()
    t.speed(0)  # Μέγιστη ταχύτητα σχεδίασης για να γίνει γρήγορα
    t.width(2)  # Αρχικό πάχος γραμμής
    t.hideturtle()  # Κρύβουμε τον κέρσορα της χελώνας (το βελάκι)

    n = 36  # Αριθμός διαφορετικών χρωμάτων που θέλουμε να φτιάξουμε
    hues = [i/n for i in range(n)]  # Δημιουργούμε 36 αποχρώσεις στον χρωματικό κύκλο (HSV)
    colors = [colorsys.hsv_to_rgb(h, 1, 1) for h in hues]  # Μετατρέπουμε HSV σε RGB (σε κλίμακα 0-1)

    # Η turtle δουλεύει σε colormode 0-1 (για RGB), οπότε δεν χρειάζεται μετατροπή
    turtle.colormode(1.0)

    radius = 10  # Αρχική απόσταση βήματος (δεν χρησιμοποιείται εδώ ενεργά)

    for i in range(360):
        color = colors[i % 6]  # Εδώ χρησιμοποιείς μόνο 6 χρώματα από τα 36 — πιθανό λάθος ή πρόθεση;
                               # Αν θες να χρησιμοποιήσεις όλα, πρέπει να βάλεις i % n
        t.pencolor(color)  # Ορίζεις το χρώμα γραμμής
        t.forward(i)  # Πηγαίνεις μπροστά κατά i pixels — όσο προχωράς μεγαλώνει η απόσταση
        t.right(59)  # Στρίβεις δεξιά κατά 59 μοίρες — φτιάχνει σπειροειδή καμπύλη
        t.width(i // 100 + 1)  # Αυξάνεις το πάχος γραμμής ανά 100 βήματα, από 1 έως 4

    screen.mainloop()  # Κρατάει το παράθυρο ανοιχτό

colorful()
